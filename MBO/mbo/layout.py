"""L2 空间+物流层（MVP）：生产计划 → 布局。

MVP 的布局是**模板 + 参数化**，不做全局 CP-SAT（判据见 docs/01 §8：30 分钟预算内
布局失败 > 3 次才升级）。每台机器一个“单元”：

    [item-source] → [belt] [belt] → [machine s×s] → [container]
                                     ↑
                               input-source 行（每条输入一行）

电力由布线器补：consumer 正交邻位放 power-node → 就近连线（超距插中继）→
找一个够得着节点的空位放 power-source → 写对称 Point2[] config。
"""

from __future__ import annotations

import math

from .model import BELT_RATE, GATES, ROT, Layout, Tile, item_cfg, point_cfg, read_points

UNIT_LEFT = 3          # 机器左侧留给 source(1) + belt(2) 的格数
NODE_RANGE = 5         # 布线器内部按 laserRange-1 保守取 5（实测 6 也通）

# split 模板（docs/16）：一个 source 直接贴在物流门上方，门把物料分流给左右两侧机器
#   反溢门：两侧优先（两侧都通按 rotation 位交替），两侧都堵才直行
#   实测 2 台石墨压机：1.360/s、两仓完全均衡、6 blocks / 18 tiles（cells 模板 10/22）
SPLIT_GATE = "underflow-gate"

# 出口合并方式（merge）：都把整条产线的产物汇到一个出口，只是出口方块不同。
#   pair   每台机器各配 2×2 容器（老行为，6 blocks / 18 tiles）
#   single 两台机器共用 1 个 2×2 容器（西机直贴、东机 1 条带）6 / 15
#   vault  两台机器共用 1 个 3×3 仓库（两侧都直贴、零带子）5 / 19
#   core   两台机器共用 1 个 3×3 核心（可读 core.items，真游戏自然出口）5 / 19
#   void   两台机器共用 1 个 1×1 物品黑洞（各 1 条带）6 / 13 —— 沙盒方块，产物被销毁
MERGE_PAIR = "pair"
MERGE_CHOICES = ("pair", "single", "vault", "core", "void")
MERGE_SINK = {"vault": ("vault", 3), "core": ("core-shard", 3),
              "single": ("container", 2), "void": ("item-void", 1)}


def _dist(a: Tile, b: Tile) -> int:
    return max(abs(a.x - b.x), abs(a.y - b.y))


def build(gd, plan, canvas=(24, 24), margin: int = 2) -> Layout:
    sizes = {name: b.size for name, b in gd.blocks.items()}
    w, h = canvas
    lay = Layout(w, h, sizes, name="mbo %s %.2f/s" % (plan.target, plan.achieved_rate),
                 description="generated by mbo 0.1.0")
    x0 = margin + UNIT_LEFT
    y = margin + 1

    counts: dict[str, int] = {}
    for name, n in plan.order:
        counts[name] = counts.get(name, 0) + n

    for name, n in counts.items():
        b = gd.block(name)
        inputs = list(b.recipe.inputs_per_second.keys()) if b.recipe else []
        if len(inputs) > b.size:
            plan.warnings.append("%s 有 %d 种输入但只有 %d 行，多出的输入未铺支线"
                                 % (name, len(inputs), b.size))
        for _ in range(n):
            y = _place_unit(lay, gd, name, b.size, inputs, x0, y, plan)
            y += 2  # 单元间留一行空隙（避免占位互卡）

    if y > h:
        raise ValueError("canvas %dx%d 放不下：需要 y>=%d" % (w, h, y))

    comps = route_power(lay, gd, anchor=(margin, margin))
    if comps and comps != 1:
        raise RuntimeError("电力连通块数=%d（应为 1）" % comps)
    return lay


# ---------------------------------------------------------------- split 模板
def _groups(plan) -> list:
    """按 plan.order 聚合同名方块，保序：[(block, 台数), ...]。"""
    counts: dict[str, int] = {}
    order: list[str] = []
    for name, n in plan.order:
        if name not in counts:
            order.append(name)
        counts[name] = counts.get(name, 0) + n
    return [(name, counts[name]) for name in order]


def split_applicable(gd, plan) -> tuple[bool, str]:
    """split 模板的适用条件：2×2 方块、单输入、同名机器成对（≥2 且偶数）。

    多输入机器（硅炉 coal+sand）不能用——一个门只分流一种物料。
    """
    for name, n in _groups(plan):
        b = gd.block(name)
        if b.size != 2:
            return False, "%s 不是 2×2（size=%d）" % (name, b.size)
        if b.recipe is None or len(b.recipe.inputs_per_second) != 1:
            return False, "%s 不是单输入机器" % name
        if n < 2 or n % 2:
            return False, "%s 有 %d 台（需 ≥2 且为偶数）" % (name, n)
    return True, ""


PORTS_CHOICES = ("both", "gate", "one")


def build_ported(gd, plan, canvas=(24, 24), margin: int = 2, ports: str = "both") -> Layout:
    """端口在外模板（docs/19）：`item-source`/`item-void` 全部落在工厂外接矩形**之外**。

    三个变体按“端口数 / 工厂格数”取舍（用户 m02384 的两条口径都满足）：

        ports="both"  每台机器各一个输入、各一个输出  → 工厂 2s² 格，4 个端口（最少格数）
        ports="gate"  一个源经反溢门分给两台，各一个输出 → 工厂 2s²+1 格，3 个端口
        ports="one"   一个源经门 + 一条带子合流到一个黑洞 → 工厂 2s²+4 格，2 个端口

    端口的合法性由 `logistics.ports_outside` 定义：只要端口格落在工厂外接矩形内就算违规。
    """
    if ports not in PORTS_CHOICES:
        raise ValueError("ports 只能是 %s，拿到 %r" % ("/".join(PORTS_CHOICES), ports))
    ok, why = split_applicable(gd, plan)
    if not ok:
        raise ValueError("ported 模板不适用：" + why)

    w, h = canvas
    sizes = {b.name: b.size for b in gd.blocks.values()}
    lay = Layout(w, h, sizes, name="mbo %s %.2f/s" % (plan.target, plan.achieved_rate),
                 description="generated by mbo 0.1.0 (ported layout, ports=%s)" % ports)

    wy = margin + 2
    for name, n in _groups(plan):
        b = gd.block(name)
        s = b.size
        item = next(iter(b.recipe.inputs_per_second))
        for k in range(n // 2):
            ty = wy + k * (2 * s + 3)
            wx = margin + 1
            gate_x = wx + s
            if ports == "both":
                # 两台机器并排相贴，端口在上下各一排
                _put(lay, plan, name, wx, ty)
                _put(lay, plan, name, wx + s, ty)
                _put(lay, plan, "item-source", wx, ty - 1, 0, item_cfg(gd, item))
                _put(lay, plan, "item-source", wx + s, ty - 1, 0, item_cfg(gd, item))
                _put(lay, plan, "item-void", wx + s - 1, ty + s)
                _put(lay, plan, "item-void", wx + 2 * s - 1, ty + s)
            elif ports == "gate":
                # 中间空一列放反溢门，源在门上方，两台机器各配一个黑洞
                _put(lay, plan, name, wx, ty)
                _put(lay, plan, name, gate_x + 1, ty)
                _put(lay, plan, SPLIT_GATE, gate_x, ty)
                _put(lay, plan, "item-source", gate_x, ty - 1, 0, item_cfg(gd, item))
                _put(lay, plan, "item-void", wx + s - 1, ty + s)
                _put(lay, plan, "item-void", gate_x + s, ty + s)
            else:
                # 单进单出：机器下方两条带子把产物送进路由器，路由器再喂给黑洞。
                # 为什么不用“中间再放一条带子”合流：实测两级带子合流只有 0.795/s
                # （侧向投料被节流），而带→路由器→黑洞是 1.287/s、eff=1.0。
                _put(lay, plan, name, wx, ty)
                _put(lay, plan, name, gate_x + 1, ty)
                _put(lay, plan, SPLIT_GATE, gate_x, ty)
                _put(lay, plan, "item-source", gate_x, ty - 1, 0, item_cfg(gd, item))
                ex = ty + s
                _put(lay, plan, "conveyor", wx + s - 1, ex, ROT["E"])
                _put(lay, plan, "router", gate_x, ex)
                _put(lay, plan, "conveyor", gate_x + 1, ex, ROT["W"])
                _put(lay, plan, "item-void", gate_x, ex + 1)

    comps = route_power(lay, gd, anchor=(margin, margin))
    if comps and comps != 1:
        raise RuntimeError("电力连通块数=%d（应为 1）" % comps)
    return lay


def build_for(gd, plan, canvas=(24, 24), margin: int = 2, layout: str = "auto",
              gate: str = SPLIT_GATE, merge: str = MERGE_PAIR) -> Layout:
    """按 layout 选模板：cells（老模板）/ split（物流分门）/ direct（10 格最小）/ auto。

    merge 只对 split 生效：每台机器各配容器（pair）还是全产线共用一个出口
    （single=2×2 容器、vault=3×3 仓库、core=3×3 核心、void=1×1 物品黑洞）。
    direct 模板固定用 item-void 当输出标记，不接受 merge 参数。
    """
    if layout == "cells":
        return build(gd, plan, canvas, margin)
    ok, why = split_applicable(gd, plan)
    if layout == "direct":
        if not ok:
            raise ValueError("direct 模板不适用：" + why)
        return build_direct(gd, plan, canvas, margin)
    if layout == "split":
        if not ok:
            raise ValueError("split 模板不适用：" + why)
        return build_split(gd, plan, canvas, margin, gate, merge)
    if layout == "ported":
        if not ok:
            raise ValueError("ported 模板不适用：" + why)
        return build_ported(gd, plan, canvas, margin, merge if merge in PORTS_CHOICES
                            else "both")
    if ok:
        return build_split(gd, plan, canvas, margin, gate, merge)
    lay = build(gd, plan, canvas, margin)
    plan.warnings.append("布局用 cells 模板：" + why)
    return lay


def build_split(gd, plan, canvas=(24, 24), margin: int = 2, gate: str = SPLIT_GATE,
                merge: str = MERGE_PAIR) -> Layout:
    """一进多出的“门”模板：主干上每 2 台机器共用一个源 + 一个物流门。

        [item-source]            ← 模块顶部一行
              ↓
          [gate]  [machine] [ctr]   ← 门左右各一台，容器贴在机器外侧
              ↓
          [belt]                  ← 还有下一对时：直行带接到下一个门
              ↓
          [gate] ...

    merge 决定产物出口（见 MERGE_* 注释）：pair=每台一个容器，其余=全产线合一个出口。
    """
    if merge not in MERGE_CHOICES:
        raise ValueError("未知 merge=%r（可选 %s）" % (merge, "/".join(MERGE_CHOICES)))
    sizes = {name: b.size for name, b in gd.blocks.items()}
    w, h = canvas
    lay = Layout(w, h, sizes, name="mbo %s %.2f/s" % (plan.target, plan.achieved_rate),
                 description="generated by mbo 0.1.0 (split layout, %s, merge=%s)"
                             % (gate, merge))

    tx = margin + 4          # 主干 x：西侧机器占 tx-2..tx-1，西容器占 tx-4..tx-3
    y = margin + 2           # 第一个门所在行，上方一行留给 item-source

    for name, n in _groups(plan):
        b = gd.block(name)
        s = b.size
        item = next(iter(b.recipe.inputs_per_second))
        for p in range(n // 2):
            gy = y + 2 * p
            if p == 0:
                _put(lay, plan, "item-source", tx, gy - 1, ROT["S"], item_cfg(gd, item))
            else:
                _put(lay, plan, "conveyor", tx, gy - 1, ROT["S"])
            _put(lay, plan, gate, tx, gy)
            # 机器中心：东侧 tx+1、西侧 tx-s（2×2 时即 tx+1 / tx-2）
            for mx in (tx + 1, tx - s):
                if not _put(lay, plan, name, mx, gy):
                    continue
                if merge == MERGE_PAIR:
                    cx = mx + s if mx > tx else mx - s   # 容器贴在机器外侧
                    if not _put(lay, plan, "container", cx, gy):
                        _put(lay, plan, "container", cx, gy + s - 1)
            if merge != MERGE_PAIR:
                _place_exit(lay, plan, tx, gy, s, merge, pair_index=p)
        y += 2 * (n // 2) + 1

    if y > h:
        raise ValueError("canvas %dx%d 放不下：需要 y>=%d" % (w, h, y))

    comps = route_power(lay, gd, anchor=(margin, margin))
    if comps and comps != 1:
        raise RuntimeError("电力连通块数=%d（应为 1）" % comps)
    return lay


def build_direct(gd, plan, canvas=(24, 24), margin: int = 2) -> Layout:
    """最小模板（docs/18）：源/黑洞当**输入输出标记**直接贴在两台机器的共用邻位上。

        [src]  [press] [press]
          ↓  ↑ ┌───────┘
        [void] ← 两台机器上下两条共用邻边，共 10 格（8 格是机器本身）

    下界：2 台 2×2 机器 = 8 格不可省；蓝图至少要 1 个输入标记 + 1 个输出标记 ⇒ ≥10 格。
    本模板正好 10 格，因此是“格数最优”。不需要门、不需要带子、不需要电力
    （v160.7 的 graphite-press 不耗电）。
    """
    sizes = {name: b.size for name, b in gd.blocks.items()}
    w, h = canvas
    lay = Layout(w, h, sizes, name="mbo %s %.2f/s" % (plan.target, plan.achieved_rate),
                 description="generated by mbo 0.1.0 (direct layout, 10-tile optimum)")
    ok, why = split_applicable(gd, plan)
    if not ok:
        raise ValueError("direct 模板不适用：" + why)

    tx = margin + 3      # 共用邻位列：西机 tx-s..tx-1，东机 tx+1..tx+2
    y = margin + 2
    for name, n in _groups(plan):
        b = gd.block(name)
        s = b.size
        item = next(iter(b.recipe.inputs_per_second))
        for p in range(n // 2):
            gy = y + 2 * p
            _put(lay, plan, "item-source", tx, gy, 0, item_cfg(gd, item))
            for mx in (tx + 1, tx - s):
                _put(lay, plan, name, mx, gy)
            _put(lay, plan, "item-void", tx, gy + 1)
    used = y + 2 * (max(n for _, n in _groups(plan)) // 2)
    if used > h:
        raise ValueError("canvas %dx%d 放不下：需要 y>=%d" % (w, h, used))
    return lay


def _put(lay: Layout, plan, name: str, x: int, y: int, rotation: int = 0, config=None) -> bool:
    """放一个方块；位置被占就记 warning 并返回 False（不静默覆盖）。"""
    if not lay.free(name, x, y):
        plan.warnings.append("%s 放不下 @(%d,%d)（被占或越界）" % (name, x, y))
        return False
    lay.add(name, x, y, rotation, config)
    return True


def _place_exit(lay: Layout, plan, tx: int, gy: int, s: int, merge: str,
                pair_index: int = 0) -> None:
    """给一对机器放合并出口（两台机器的产物汇到同一个方块）。

    几何：机器底边在 gy+s-1；出口行 ey=gy+s（门正下方一格留空，避免堵住直行位）。
      vault/core 3×3 @ (tx-1, ey)：同时贴住西机 (tx-1,gy+s-1) 与东机 (tx+1,gy+s-1)
      single     2×2 @ (tx-1, ey)：西机直贴；东机用 1 条带 (tx+1,ey) rot=W 送进来
      void       1×1 @ (tx, ey)  ：两侧各 1 条带（西 rot=E、东 rot=W）
    """
    ey = gy + s
    block, size = MERGE_SINK[merge]
    if merge in ("vault", "core"):
        # 3×3 以中心格存坐标：中心 (tx, gy+s+1) ⇒ 覆盖 tx-1..tx+1 × gy+s..gy+s+2，
        # 顶行正好贴住两台机器的底边（(tx-1,gy+s-1) 与 (tx+1,gy+s-1)）。
        _put(lay, plan, block, tx, gy + s + 1)
        return
    if merge == "single":
        _put(lay, plan, "container", tx - 1, ey)
        _put(lay, plan, "conveyor", tx + 1, ey, ROT["W"])
        return
    # void：1×1 黑洞，两侧各一条带送进去
    _put(lay, plan, "conveyor", tx - 1, ey, ROT["E"])
    _put(lay, plan, "conveyor", tx + 1, ey, ROT["W"])
    _put(lay, plan, block, tx, ey)


def _place_unit(lay: Layout, gd, name: str, size: int, inputs: list, x: int, y: int, plan) -> int:
    """放一台机器及其输入支线、输出容器；返回下一个可用的 y。"""
    mx, my = x, y
    for k, item in enumerate(inputs[:size]):
        row = my + k
        src_x = mx - UNIT_LEFT
        if lay.free("item-source", src_x, row):
            lay.add("item-source", src_x, row, 0, item_cfg(gd, item))
        else:
            plan.warnings.append("%s 的第 %d 行输入（%s）没有空位放 item-source" % (name, k, item))
            continue
        for cx in range(src_x + 1, mx):
            if lay.free("conveyor", cx, row):
                lay.add("conveyor", cx, row, ROT["E"])
    if not lay.free(name, mx, my):
        raise ValueError("overlap/out-of-bounds: %s@(%d,%d)" % (name, mx, my))
    lay.add(name, mx, my)

    # 输出容器：优先机器右侧，其次右上，再螺旋找
    for cand in ((mx + size, my), (mx + size, my + 1)):
        if lay.free("container", *cand):
            lay.add("container", *cand)
            break
    else:
        spot = lay.find_free("container", mx + size, my, radius=4)
        if spot is None:
            plan.warnings.append("%s 的输出容器无处安放" % name)
        else:
            lay.add("container", *spot)
    return max(my + size, my + 1)


# ---------------------------------------------------------------- 电力布线
def route_power(lay: Layout, gd, anchor=(0, 0)) -> int:
    consumers = [t for t in lay.tiles if gd.block(t.block).consumes_power]
    if not consumers:
        return 0

    nodes: list[Tile] = []
    links: dict[int, list[Tile]] = {}

    def link(a: Tile, b: Tile):
        links.setdefault(id(a), []).append(b)
        links.setdefault(id(b), []).append(a)

    # 1) 每个 consumer 的正交邻位放一个 node（优先上方/左方，保持布局紧凑）
    for c in consumers:
        pos = None
        for cand in _neighbor_slots(lay, c):
            if lay.free("power-node", *cand):
                pos = cand
                break
        if pos is None:
            raise RuntimeError("%s@(%d,%d) 周围没有空位放 power-node" % (c.block, c.x, c.y))
        node = lay.add("power-node", *pos)
        nodes.append(node)

    # 2) 并查集式连通：每次合并两个最近的连通块，超距时插中继节点
    comps = [[nd] for nd in nodes]
    while len(comps) > 1:
        best = None
        for i in range(len(comps)):
            for j in range(i + 1, len(comps)):
                for a in comps[i]:
                    for b in comps[j]:
                        d = _dist(a, b)
                        if best is None or d < best[0]:
                            best = (d, i, j, a, b)
        d, i, j, a, b = best
        if d <= NODE_RANGE:
            link(a, b)
        else:
            relay = _place_relay(lay, a, b)
            if relay is None:
                raise RuntimeError("无法在 (%d,%d)-(%d,%d) 之间放中继节点" % (a.x, a.y, b.x, b.y))
            nodes.append(relay)
            link(a, relay)
            link(relay, b)
        merged = comps[i] + comps[j] + ([relay] if d > NODE_RANGE else [])
        comps = [c for k, c in enumerate(comps) if k not in (i, j)] + [merged]

    # 3) 电源：找离 anchor 最近、且够得着某个节点的空位
    src = None
    bestd = None
    for nd in nodes:
        for cand in _ring(lay, nd, NODE_RANGE):
            if not lay.free("power-source", *cand):
                continue
            dd = abs(cand[0] - anchor[0]) + abs(cand[1] - anchor[1])
            if bestd is None or dd < bestd:
                bestd, src = dd, cand
    if src is None:
        raise RuntimeError("找不到放 power-source 的位置（离节点 %d 格内）" % NODE_RANGE)
    source = lay.add("power-source", *src)
    nearest = min(nodes, key=lambda nd: _dist(nd, source))
    link(source, nearest)

    # 4) 写对称 config
    for t in nodes + [source]:
        pts = sorted((o.x - t.x, o.y - t.y) for o in links.get(id(t), []))
        lay.set_config(t, point_cfg(pts))

    # 5) 自检：按 config 重建连通性（单向 link 是真实存在过的 bug 类型）
    for t in nodes + [source]:
        for dx, dy in read_points(t.config):
            other = lay.tile_at(t.x + dx, t.y + dy)
            if other is None:
                raise RuntimeError("%s@(%d,%d) 的 link 指向空位" % (t.block, t.x, t.y))
            if other.block not in ("power-node", "power-source"):
                raise RuntimeError("%s@(%d,%d) 的 link 指向 %s"
                                   % (t.block, t.x, t.y, other.block))
            if not any(o.x == t.x and o.y == t.y for o in _linked_nodes(lay, other)):
                raise RuntimeError("%s@(%d,%d) 的单向 link 未对称" % (t.block, t.x, t.y))
    return _components(lay, nodes + [source])


def _neighbor_slots(lay: Layout, tile: Tile):
    from .model import DIRV

    out = []
    cells = sorted(lay.cells(tile.block, tile.x, tile.y), key=lambda c: (c[1], c[0]))
    for cx, cy in cells:
        for dx, dy in ((0, -1), (-1, 0), (1, 0), (0, 1)):
            out.append((cx + dx, cy + dy))
    seen, uniq = set(), []
    for p in out:
        if p not in seen:
            seen.add(p)
            uniq.append(p)
    return uniq


def _ring(lay: Layout, tile: Tile, radius: int):
    for r in range(1, radius + 1):
        for dx in range(-r, r + 1):
            for dy in range(-r, r + 1):
                if max(abs(dx), abs(dy)) != r:
                    continue
                yield tile.x + dx, tile.y + dy


def _place_relay(lay: Layout, a: Tile, b: Tile):
    best, bestd = None, None
    for r in range(1, NODE_RANGE + 1):
        for dx in range(-r, r + 1):
            for dy in range(-r, r + 1):
                if max(abs(dx), abs(dy)) != r:
                    continue
                cand = (a.x + dx, a.y + dy)
                if _dist_xy(cand, (b.x, b.y)) > NODE_RANGE:
                    continue
                if not lay.free("power-node", *cand):
                    continue
                d = _dist_xy(cand, (a.x, a.y)) + _dist_xy(cand, (b.x, b.y))
                if bestd is None or d < bestd:
                    best, bestd = cand, d
        if best:
            break
    return lay.add("power-node", *best) if best else None


def _dist_xy(p, q) -> int:
    return max(abs(p[0] - q[0]), abs(p[1] - q[1]))


def _linked_nodes(lay: Layout, t: Tile):
    """config 里指向的方块（power 图里只有 node/source 有意义）。"""
    out = []
    for dx, dy in read_points(t.config):
        o = lay.tile_at(t.x + dx, t.y + dy)
        if o is not None:
            out.append(o)
    return out


def _components(lay: Layout, power_tiles: list) -> int:
    """按 config 连边数连通块（只算节点/电源）。"""
    ids = {id(t): t for t in power_tiles}
    seen, comps = set(), 0
    for t in power_tiles:
        if id(t) in seen:
            continue
        comps += 1
        stack = [t]
        while stack:
            cur = stack.pop()
            if id(cur) in seen:
                continue
            seen.add(id(cur))
            for o in _linked_nodes(lay, cur):
                if id(o) in ids and id(o) not in seen:
                    stack.append(o)
    return comps
